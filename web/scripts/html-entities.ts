// writes the HTML named character references that markdown-it 15 decodes (through the entities package it
// imports) as a Swift source file, so the Swift markdown tokenizer decodes the same entities.
// run: npm run html-entities, which writes ../App/Sources/Core/Markdown/HTMLEntities.swift
//
// markdown-it only ever decodes a whole `&name;` in strict mode (entity rule and unescapeAll), and in strict mode
// the entities decoder accepts exactly the names its trie holds followed by `;`. so a table of the trie's names
// gives the same result. the names are read by walking the trie with the package's own determineBranch, and each
// one is checked against decodeHTMLStrict before it is written.
import { writeFileSync } from 'node:fs';
import { decodeHTMLStrict, determineBranch, htmlDecodeTree as tree } from 'entities/decode';

// node_modules/entities/dist/internal/bin-trie-flags.js (8.1.0)
const VALUE_LENGTH = 49152;
const FLAG13 = 8192;
const BRANCH_LENGTH = 8064;
const JUMP_TABLE = 127;
const VALUE_MASK = 8191;

const target = process.argv[2];
if (!target) throw new Error('Give the file to write.');

const found = new Map<string, number[]>();
function walk(index: number, name: string): void {
  const current = tree[index]!;
  // a compact run spells out a fixed stretch of characters
  if ((current & (VALUE_LENGTH | FLAG13)) === FLAG13) {
    const runLength = (current & BRANCH_LENGTH) >> 7;
    let spelled = String.fromCharCode(current & JUMP_TABLE);
    for (let consumed = 1; consumed < runLength; consumed++) {
      const packed = tree[index + 1 + ((consumed - 1) >> 1)]!;
      spelled += String.fromCharCode((packed >> (((consumed - 1) & 1) << 3)) & 0xff);
    }
    walk(index + 1 + (runLength >> 1), name + spelled);
    return;
  }
  const valueLength = current >>> 14;
  if (valueLength !== 0) {
    const units = valueLength === 1 ? [current & VALUE_MASK] : valueLength === 2 ? [tree[index + 1]!] : [tree[index + 1]!, tree[index + 2]!];
    found.set(name, units);
    if (valueLength === 1) return;
  }
  for (let char = 0x21; char < 0x7f; char++) {
    const next = determineBranch(tree, current, index + (valueLength || 1), char);
    if (next >= 0) walk(next, name + String.fromCharCode(char));
  }
}
walk(0, '');

const names = [...found.keys()].sort();
for (const name of names) {
  const expected = String.fromCharCode(...found.get(name)!);
  if (decodeHTMLStrict(`&${name};`) !== expected) throw new Error(`decodeHTMLStrict disagrees on ${name}`);
}
// the WHATWG list has 2231 entries, 106 of them the legacy forms without a semicolon of names also listed with one
if (names.length !== 2125) throw new Error(`expected 2125 names, found ${names.length}`);

const lines = names.map((name) => `${name} ${found.get(name)!.map((unit) => unit.toString(16)).join(' ')}`);
writeFileSync(
  target,
  `// Generated by web/scripts/html-entities.ts from the entities package (8.1.0) markdown-it 15 uses. Do not edit.
// Every HTML named character reference: the name, then the UTF-16 code units it decodes to, in hex.
import Foundation

nonisolated enum HTMLEntities {
    /// The text \`&name;\` decodes to in strict mode, by the name without \`&\` and \`;\`.
    static let table: [JSKey: [UInt16]] = {
        var table: [JSKey: [UInt16]] = [:]
        for line in list.split(separator: "\\n") {
            let parts = line.split(separator: " ")
            table[JSKey(String(parts[0]))] = parts.dropFirst().map { UInt16($0, radix: 16)! }
        }
        return table
    }()

    private static let list = """
${lines.join('\n')}
"""
}
`,
);
console.log(`wrote ${names.length} names`);
