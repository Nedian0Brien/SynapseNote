// writes which code points markdown-it 15 counts as punctuation or symbols (its isPunctCharCode, from the
// uc.micro tables it uses) as Swift ranges, so the Swift tokenizer decides emphasis exactly as markdown-it does.
// run: npm run markdown-unicode, which writes ../App/Sources/Core/Markdown/MarkdownPunctuation.swift
import { writeFileSync } from 'node:fs';
import * as ucmicro from 'uc.micro';

const target = process.argv[2];
if (!target) throw new Error('Give the file to write.');
// markdown-it's fromCodePoint and isPunctChar, as in src/common/utils.ts
const fromCodePoint = (c: number): string => {
  if (c > 0xffff) {
    c -= 0x10000;
    return String.fromCharCode(0xd800 + (c >> 10), 0xdc00 + (c & 0x3ff));
  }
  return String.fromCharCode(c);
};
const isPunct = (c: number): boolean => {
  const ch = fromCodePoint(c);
  return ucmicro.P.test(ch) || ucmicro.S.test(ch);
};
const ranges: Array<[number, number]> = [];
for (let c = 0; c <= 0x10ffff; c++) {
  if (!isPunct(c)) continue;
  const last = ranges[ranges.length - 1];
  if (last && last[1] === c - 1) last[1] = c;
  else ranges.push([c, c]);
}
const rows: string[] = [];
for (let i = 0; i < ranges.length; i += 6)
  rows.push('        ' + ranges.slice(i, i + 6).map(([a, b]) => `(0x${a.toString(16)}, 0x${b.toString(16)})`).join(', ') + ',');
writeFileSync(
  target,
  `// Generated by web/scripts/markdown-unicode.ts from the uc.micro tables markdown-it 15 uses. Do not edit.
nonisolated enum MarkdownPunctuation {
    /// Code points markdown-it's isPunctCharCode accepts: Unicode punctuation (P) and symbols (S).
    static func contains(_ code: UInt32) -> Bool {
        var low = 0
        var high = ranges.count - 1
        while low <= high {
            let mid = (low + high) / 2
            if code < ranges[mid].0 { high = mid - 1 } else if code > ranges[mid].1 { low = mid + 1 } else { return true }
        }
        return false
    }

    private static let ranges: [(UInt32, UInt32)] = [
${rows.join('\n')}
    ]
}
`,
);
console.log(`wrote ${ranges.length} ranges`);
